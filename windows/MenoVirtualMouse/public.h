#pragma once

#if defined(_KERNEL_MODE) || defined(_NTDDK_) || defined(_WDMDDK_)
#include <ntddk.h>
#else
#include <windows.h>
#endif

#define MENO_VIRTUAL_MOUSE_ABI 6u
#define MENO_VIRTUAL_MOUSE_REPORT_VERSION 2u
#define MENO_VIRTUAL_MOUSE_MAX_BATCH 15u
#define MENO_VIRTUAL_MOUSE_QUEUE_CAPACITY 64u
#define MENO_VIRTUAL_MOUSE_OUTPUT_DATA_SIZE 126u
#define MENO_VIRTUAL_KEYBOARD_MAX_KEYS 6u
#define MENO_VIRTUAL_KEYBOARD_WATCHDOG_MS 500u
#define MENO_VIRTUAL_KEYBOARD_TIMER_MS 100u

#define MENO_VIRTUAL_MOUSE_VID 0x4D45u
#define MENO_VIRTUAL_MOUSE_PID 0x4E4Fu
#define MENO_VIRTUAL_MOUSE_VERSION_MAJOR 2u
#define MENO_VIRTUAL_MOUSE_VERSION_MINOR 3u
#define MENO_VIRTUAL_MOUSE_VERSION_PATCH 5u
#if MENO_VIRTUAL_MOUSE_VERSION_MAJOR > 255u || MENO_VIRTUAL_MOUSE_VERSION_MINOR > 15u || MENO_VIRTUAL_MOUSE_VERSION_PATCH > 15u
#error MENO_VIRTUAL_MOUSE_DEVICE_VERSION allocates 8 bits to major and 4 bits each to minor and patch
#endif
#define MENO_VIRTUAL_MOUSE_DEVICE_VERSION \
    ((MENO_VIRTUAL_MOUSE_VERSION_MAJOR << 8) \
        | (MENO_VIRTUAL_MOUSE_VERSION_MINOR << 4) \
        | MENO_VIRTUAL_MOUSE_VERSION_PATCH)

#define MENO_VIRTUAL_MOUSE_REPORT_ID 0x01u
#define MENO_VIRTUAL_KEYBOARD_REPORT_ID 0x02u
#define MENO_VIRTUAL_MOUSE_CONTROL_REPORT_ID 0x10u
#define MENO_VIRTUAL_MOUSE_OUTPUT_REPORT_ID 0x11u
#define MENO_VIRTUAL_MOUSE_CONTROL_USAGE_PAGE 0xFF00u
#define MENO_VIRTUAL_MOUSE_CONTROL_USAGE 0x0001u

#define MENO_VIRTUAL_MOUSE_COMMAND_SUBMIT 0x01u
#define MENO_VIRTUAL_MOUSE_COMMAND_RESET 0x02u
#define MENO_VIRTUAL_KEYBOARD_COMMAND_STATE 0x03u

#define MENO_VIRTUAL_MOUSE_CAP_ABSOLUTE_XY 0x00000001u
#define MENO_VIRTUAL_MOUSE_CAP_BUTTONS 0x00000002u
#define MENO_VIRTUAL_MOUSE_CAP_VERTICAL_WHEEL 0x00000004u
#define MENO_VIRTUAL_MOUSE_CAP_BATCH 0x00000008u
#define MENO_VIRTUAL_MOUSE_CAP_UMDF 0x00000010u
#define MENO_VIRTUAL_MOUSE_CAP_KEYBOARD 0x00000020u
#define MENO_VIRTUAL_MOUSE_CAP_KEYBOARD_WATCHDOG 0x00000040u
#define MENO_VIRTUAL_MOUSE_CAP_OUTPUT_REPORT 0x00000080u
#define MENO_VIRTUAL_MOUSE_CAP_PATH_DIAGNOSTICS 0x00000100u

/* Absolute X/Y are reported in the HID logical range 0..32767; Windows maps
   the range onto the desktop without pointer ballistics. */
#define MENO_VIRTUAL_MOUSE_ABSOLUTE_MAX 32767u

#pragma pack(push, 1)

typedef struct _MENO_VIRTUAL_MOUSE_INFO {
    USHORT Abi;
    USHORT VersionMajor;
    USHORT VersionMinor;
    USHORT VersionPatch;
    ULONG Capabilities;
    USHORT MaximumBatch;
    USHORT QueueCapacity;
    USHORT MouseReportSize;
    USHORT KeyboardReportSize;
    ULONGLONG AcceptedReports;
    ULONG MaximumQueueDepth;
    ULONG MergeCount;
    ULONG CurrentQueueDepth;
    ULONGLONG OutputWrites;
    USHORT LastOutputSequence;
    USHORT DiagnosticsReserved;
    ULONGLONG LastWriteEnterQpc;
    ULONGLONG LastWriteExitQpc;
    ULONGLONG QpcFrequency;
    ULONG LastWriteDurationUs;
    ULONG MaximumWriteDurationUs;
    LONG LastWriteStatus;
} MENO_VIRTUAL_MOUSE_INFO, *PMENO_VIRTUAL_MOUSE_INFO;

typedef struct _MENO_VIRTUAL_MOUSE_SAMPLE {
    USHORT X;
    USHORT Y;
    CHAR Wheel;
    UCHAR Buttons;
    UCHAR Flags;
    UCHAR Reserved;
} MENO_VIRTUAL_MOUSE_SAMPLE, *PMENO_VIRTUAL_MOUSE_SAMPLE;

typedef struct _MENO_VIRTUAL_MOUSE_OUTPUT_REPORT {
    UCHAR ReportId;
    UCHAR Version;
    UCHAR Command;
    UCHAR Count;
    UCHAR Flags;
    USHORT Sequence;
    UCHAR Payload[MENO_VIRTUAL_MOUSE_OUTPUT_DATA_SIZE];
} MENO_VIRTUAL_MOUSE_OUTPUT_REPORT, *PMENO_VIRTUAL_MOUSE_OUTPUT_REPORT;

typedef struct _MENO_VIRTUAL_MOUSE_HID_REPORT {
    UCHAR ReportId;
    UCHAR Buttons;
    USHORT X;
    USHORT Y;
    CHAR Wheel;
} MENO_VIRTUAL_MOUSE_HID_REPORT, *PMENO_VIRTUAL_MOUSE_HID_REPORT;

typedef struct _MENO_VIRTUAL_KEYBOARD_HID_REPORT {
    UCHAR ReportId;
    UCHAR Modifiers;
    UCHAR Reserved;
    UCHAR Keys[MENO_VIRTUAL_KEYBOARD_MAX_KEYS];
} MENO_VIRTUAL_KEYBOARD_HID_REPORT, *PMENO_VIRTUAL_KEYBOARD_HID_REPORT;

#pragma pack(pop)

#define MENO_VIRTUAL_MOUSE_CONTROL_REPORT_SIZE 133u
#define MENO_VIRTUAL_MOUSE_FEATURE_PAYLOAD_SIZE \
    (MENO_VIRTUAL_MOUSE_CONTROL_REPORT_SIZE - 1u)
#define MENO_VIRTUAL_MOUSE_OUTPUT_REPORT_SIZE 133u
#define MENO_VIRTUAL_MOUSE_OUTPUT_PAYLOAD_SIZE \
    (MENO_VIRTUAL_MOUSE_OUTPUT_REPORT_SIZE - 1u)
#define MENO_VIRTUAL_MOUSE_HID_REPORT_SIZE 7u
#define MENO_VIRTUAL_KEYBOARD_HID_REPORT_SIZE 9u
#define MENO_VIRTUAL_HID_MAX_REPORT_SIZE MENO_VIRTUAL_KEYBOARD_HID_REPORT_SIZE
